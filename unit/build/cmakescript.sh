#!/bin/bash

./cmakeclean.sh

[[ ! "$PONNI_DEBUG" == "ON" ]] && PONNI_CXX_FLAGS+=";-DNDEBUG"
CMAKE_COMMAND=(cmake -Wno-dev)
CMAKE_COMMAND+=(-DPONNI_CXX_FLAGS="$PONNI_CXX_FLAGS")
CMAKE_COMMAND+=(-DPONNI_LINK_FLAGS="$PONNI_LINK_FLAGS")
CMAKE_COMMAND+=(-DPONNI_ENABLE_COVERAGE="$PONNI_COVERAGE")
[[ ! "$PONNI_BACKEND" == "" ]] && CMAKE_COMMAND+=(-D${PONNI_BACKEND}=ON)
[[ ! "$PONNI_ARCH"    == "" ]] && CMAKE_COMMAND+=(-D${PONNI_ARCH}=ON)
if [[ "$PONNI_BACKEND" == "Kokkos_ENABLE_CUDA" ]]; then
  CMAKE_COMMAND+=(-DKokkos_ENABLE_CUDA=ON -DKokkos_ENABLE_CUDA_CONSTEXPR=ON)
else
  CMAKE_COMMAND+=(-DKokkos_ENABLE_CUDA=OFF -DKokkos_ENABLE_CUDA_CONSTEXPR=OFF)
fi
[[ "$PONNI_DEBUG" == "ON" ]] && CMAKE_COMMAND+=(-DKokkos_ENABLE_DEBUG=ON -DKokkos_ENABLE_DEBUG_BOUNDS_CHECK=ON)
CMAKE_COMMAND+=(..)

echo "${CMAKE_COMMAND[@]}"

"${CMAKE_COMMAND[@]}"
